function writeTable(sheet, title, headers, rows, tableName) {
  sheet.showGridLines = false;
  sheet.getRange("A1").values = [[title]];
  sheet.getRange("A1").format = {
    font: { bold: true, size: 15, color: "#111827" },
  };

  const colCount = headers.length;
  const rowCount = rows.length + 1;
  const range = sheet.getRangeByIndexes(2, 0, rowCount, colCount);
  range.values = [headers, ...rows];
  range.format.borders = { preset: "all", style: "thin", color: "#D1D5DB" };

  const headerRange = sheet.getRangeByIndexes(2, 0, 1, colCount);
  headerRange.format = {
    fill: "#1F2937",
    font: { bold: true, color: "#FFFFFF" },
    wrapText: true,
  };

  const dataRange = sheet.getRangeByIndexes(3, 0, rows.length, colCount);
  dataRange.format = { wrapText: false };
  sheet.tables.add(range.address, true, tableName).style = "TableStyleMedium2";
  sheet.freezePanes.freezeRows(3);
  sheet.getUsedRange().format.autofitColumns();
  sheet.getUsedRange().format.autofitRows();
}

function styleNumberColumns(sheet, ranges) {
  for (const rangeName of ranges) {
    sheet.getRange(rangeName).format.numberFormat = "0.00";
  }
}

